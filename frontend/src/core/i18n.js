export const getStatusStyle = (status) => {
  if (status === 'Completed' || status === 'Done') return TASK_STATUS_CONFIG.Completed;
  if (status === 'Remaining' || status === 'In Progress') return TASK_STATUS_CONFIG.Remaining;
  if (status === 'Not Completed') return TASK_STATUS_CONFIG['Not Completed'];
  return TASK_STATUS_CONFIG.Planned;
};

